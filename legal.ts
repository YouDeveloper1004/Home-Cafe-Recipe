export function isAtLeast14(value:string,now=new Date()):boolean {
  const match=/^(\d{4})-(\d{2})-(\d{2})$/.exec(value.trim());
  if(!match)return false;
  const [year,month,day]=match.slice(1).map(Number);
  const born=new Date(Date.UTC(year,month-1,day));
  if(born.getUTCFullYear()!==year||born.getUTCMonth()!==month-1||born.getUTCDate()!==day)return false;
  born.setUTCFullYear(year+14);
  return born.getTime()<=now.getTime();
}

